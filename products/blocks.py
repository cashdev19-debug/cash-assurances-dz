from wagtail import blocks
from wagtail.images.blocks import ImageChooserBlock
from wagtail.snippets.blocks import SnippetChooserBlock

class oneProductBlock(blocks.StructBlock):
    products = blocks.ListBlock(
            blocks.StructBlock([
                    ("title",blocks.CharBlock()),
                    ("text",blocks.RichTextBlock(required=False)),
                    ("image",ImageChooserBlock()),
                    ("button_text",blocks.CharBlock()),
                    ("linked_page",blocks.PageChooserBlock()),
                ])
    )
    class Meta:
        template = "products/blocks/one_product_block.html"
        icon = "0-square-fill"
       

class multipleProducstBlock(blocks.StructBlock):
    title = blocks.CharBlock()
    subtitle = blocks.CharBlock(required=False)
    products = blocks.ListBlock(
                blocks.StructBlock([
                    ("title",blocks.CharBlock()),
                    ("image",ImageChooserBlock()),
                    ("button_text",blocks.CharBlock()),
                    ("linked_page",blocks.PageChooserBlock()),
                ])
    )
    class Meta:
        template = "products/blocks/multiple_products_block.html"
        icon = "0-square-fill"
       


class autoGeneratedProducstBlock(blocks.StructBlock):
    categories = blocks.ListBlock(
        SnippetChooserBlock("products.ProductCategory"),
        min_num=1,
        help_text="Select one or more product categories",
    )
    class Meta:
        template = "products/blocks/auto_generated_producst_block.html"
        icon = "0-square-fill"
       

